/* Builds gst-fetch/page.js from 1Go's portal page script (company-software-suite/src/portalpreload.js).
   The portal steps are the ones 1Go has tested on the GST portal, the Income Tax portal and TRACES; here they run inside the
   helper's own browser. Only three things change: the Electron message channel becomes the helper's channel, the script runs in
   the top page only, and the words on the progress bar say Smart Auditing.
   Use:  node tools/make-page.mjs ../../company-software-suite/src/portalpreload.js            */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const src = process.argv[2];
if (!src) { console.error('Give the path of 1Go src/portalpreload.js'); process.exit(1); }
let s = fs.readFileSync(src, 'utf8');
const req = "const { ipcRenderer } = require('electron');";
if (!s.includes(req)) { console.error('The page script no longer starts with the Electron channel line; check it by hand.'); process.exit(1); }
s = s.replace(req, '/* (helper) the message channel: see the top of this file */');
s = s.replace(/Documents\\\\1Go portal downloads/g, 'Documents\\\\Smart Auditing portal downloads').replace(/1Go/g, 'Smart Auditing');
const head = `/* Smart Auditing portal helper: the portal steps, run in the helper's browser page.
   GENERATED by tools/make-page.mjs from 1Go src/portalpreload.js. Do not edit here; change 1Go's script and build again. */
(() => {
if (window.top !== window || window.__saPortal) return;
Object.defineProperty(window, '__saPortal', { value: 1 });
const __on = {};
const ipcRenderer = {
  invoke: (ch, ...a) => window.__saPortalCall(String(ch), a),
  on: (ch, fn) => { (__on[ch] = __on[ch] || []).push(fn); }
};
Object.defineProperty(window, '__saPortalEmit', { value: (ch, a) => (__on[ch] || []).forEach(f => { try { f({}, a); } catch (e) {} }) });
`;
const out = head + s + '\n})();\n';
const dest = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'page.js');
fs.writeFileSync(dest, out);
console.log('page.js written (' + out.length + ' bytes)');
